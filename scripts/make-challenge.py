# Writes DelegusCheckChallenge/ (and its root DelegusCheckChallenge.lean): the
# statements-only challenge for the independent comparison (`con-leche
# --compare`, `lake comparator`).
#
#   python3 scripts/make-challenge.py [--check]
#
# It is the model's own source, module for module, with every public
# theorem's proof replaced by `sorry` and private theorems (used only inside
# proofs) left out. Definitions are kept exactly as written, and module
# boundaries are kept too (Lean names auxiliary definitions per module), so
# the comparison tools can check that each definition the statements use is
# the same in the challenge as in the proved development. Outside its own
# modules it imports only Lean core (`Lean.Data.Json`).
#
# --check: fail if the committed file is not what this script writes.

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORDER = ["Basic", "Kernel", "Theorems", "Inputs", "Syntax", "Readings", "Htu", "Jcs", "Grant", "Rules",
         "Evaluate", "Staged", "Facts", "Phase1", "Phase1Rows", "Historical", "Effects", "Revocation", "Replay"]
OUT_DIR = ROOT / "DelegusCheckChallenge"
OUT_ROOT = ROOT / "DelegusCheckChallenge.lean"

DECL_START = re.compile(r"^(@\[[^\]]*\]\s*)?(private\s+)?(theorem|lemma)\s+([A-Za-z0-9_.']+)")
TOP = re.compile(r"^\S")


def proof_start(text: str) -> int:
    """Index of the `:=` that begins the proof, at bracket depth 0, not a `let`/`have` binding.
    Returns -1 for an equation-style proof (`| pat => ...`)."""
    depth = 0
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if text.startswith("--", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if text.startswith("/-", i):
            j = text.find("-/", i)
            i = n if j < 0 else j + 2
            continue
        if c == '"':
            i += 1
            while i < n and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
            i += 1
            continue
        if c == "'" and i + 2 < n and text[i + 2] == "'":
            i += 3
            continue
        if c in "([{⟨":
            depth += 1
        elif c in ")]}⟩":
            depth -= 1
        elif depth == 0 and text.startswith(":=", i):
            before = text[:i]
            if not re.search(r"\b(let|have)\s+[A-Za-z0-9_']+\s*(:[^=]*)?$", before.split("\n")[-1]):
                return i
        elif depth == 0 and c == "\n" and re.match(r"\n\s+\|", text[i:]):
            return -1 - i
        i += 1
    raise ValueError("no proof found")


def transform(src: str) -> str:
    lines = src.split("\n")
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("import "):
            out.append(line.replace("import DelegusCheckSpec.", "import DelegusCheckChallenge."))
            i += 1
            continue
        m = DECL_START.match(line)
        if not m:
            out.append(line)
            i += 1
            continue
        # the declaration runs to the next top-level line
        j = i + 1
        while j < len(lines) and not TOP.match(lines[j]):
            j += 1
        decl = "\n".join(lines[i:j])
        # drop a trailing blank tail into the output after the declaration
        if m.group(2):
            # private: used only inside proofs; left out
            pass
        else:
            k = proof_start(decl)
            if k >= 0:
                sig = decl[:k].rstrip()
            else:
                sig = decl[: -1 - k].rstrip()
            out.append(sig + " := sorry")
        i = j
    return "\n".join(out)


HEADER = """-- Generated by scripts/make-challenge.py from DelegusCheckSpec/{name}.lean: the
-- definitions exactly as written, every public theorem's proof replaced by `sorry`.
-- Do not edit by hand.
"""


def outputs() -> dict:
    files = {}
    for name in ORDER:
        src = (ROOT / "DelegusCheckSpec" / f"{name}.lean").read_text()
        files[OUT_DIR / f"{name}.lean"] = HEADER.format(name=name) + transform(src).rstrip() + "\n"
    names = []
    for name in ORDER:
        for line in (ROOT / "DelegusCheckSpec" / f"{name}.lean").read_text().split("\n"):
            m = DECL_START.match(line)
            if m and not m.group(2):
                names.append("DelegusCheck." + m.group(4))
    files[ROOT / "comparator.json"] = json.dumps({
        "challenge_module": "DelegusCheckChallenge",
        "solution_module": "DelegusCheckSpec",
        "theorem_names": names,
        "definition_names": [],
        "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"],
        "external_kernels": {"nanoda": ["nanoda_bin"]},
    }, indent=2) + "\n"
    files[OUT_ROOT] = """/-
Copyright 2026 Inam Haq. Licensed under the Apache License, Version 2.0.

The statements-only challenge for the independent comparison: the model's
definitions, exactly as in `DelegusCheckSpec/`, and every public theorem
with its proof replaced by `sorry`. Generated by `scripts/make-challenge.py`;
do not edit by hand. Outside its own modules it imports only Lean core.
-/
""" + "".join(f"import DelegusCheckChallenge.{n}\n" for n in ORDER)
    return files


def main() -> int:
    files = outputs()
    if "--check" in sys.argv:
        stale = [p.name for p, t in files.items() if not p.exists() or p.read_text() != t]
        if stale:
            print(f"challenge out of date ({', '.join(stale)}); run python3 scripts/make-challenge.py")
            return 1
        print("challenge is current")
        return 0
    OUT_DIR.mkdir(exist_ok=True)
    for p, t in files.items():
        p.write_text(t)
    print(f"wrote {len(files)} challenge files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
